"""Compose the plain-text email replies.

The replies are built from templates rather than generated by a model: every
number and date in them comes straight from the site, so they cannot drift
from what was actually found and attached.
"""
from __future__ import annotations

from datetime import datetime
from typing import List, Optional

from .models import DOC_TYPES, SINGULAR, Document, FetchResult, MatterMetadata
from .packager import archive_name

TYPES_LIST = "Exhibits, Key Documents, Other Documents, Transcripts, or Recordings"
EXAMPLE_REQUEST = "Can you give me Other Documents files from M12205?"


def format_date(value: str) -> str:
    """'04/07/2025' -> 'April 7, 2025'. Leaves anything else untouched."""
    try:
        d = datetime.strptime(value.strip(), "%m/%d/%Y")
    except ValueError:
        return value
    return f"{d:%B} {d.day}, {d.year}"


def count_of(n: int, doc_type: str) -> str:
    return f"{n} {SINGULAR[doc_type] if n == 1 else doc_type}"


def join_words(items: List[str], conjunction: str = "and") -> str:
    if len(items) <= 1:
        return "".join(items)
    if len(items) == 2:
        return f"{items[0]} {conjunction} {items[1]}"
    return f"{', '.join(items[:-1])}, {conjunction} {items[-1]}"


def greeting_name(display_name: str) -> str:
    first = display_name.strip().split(" ")[0].strip('"\',') if display_name.strip() else ""
    return first if first and "@" not in first else "there"


def matter_summary(meta: MatterMetadata) -> str:
    sentences = []
    if meta.title:
        sentences.append(f"{meta.matter} is about the {meta.title.rstrip('.')}.")
    else:
        sentences.append(f"I found {meta.matter} on the UARB site.")
    if meta.description:
        sentences.append(meta.description if meta.description.endswith(".") else meta.description + ".")
    if meta.category and meta.type and meta.category.lower() != "other":
        sentences.append(f"It relates to {meta.category} within the {meta.type} category.")
    elif meta.type and meta.category:
        sentences.append(f"It falls under the {meta.type} category.")
    elif meta.type or meta.category:
        sentences.append(f"It falls under the {meta.type or meta.category} category.")
    if meta.date_received and meta.date_final:
        sentences.append(
            f"The matter had an initial filing on {format_date(meta.date_received)} "
            f"and a final filing on {format_date(meta.date_final)}."
        )
    elif meta.date_received:
        sentences.append(
            f"The matter had an initial filing on {format_date(meta.date_received)}; "
            "no final filing date is listed yet."
        )
    if meta.status and meta.outcome:
        sentences.append(f"Its status is {meta.status}, with the outcome “{meta.outcome}”.")
    elif meta.status:
        sentences.append(f"Its status is {meta.status}.")
    return " ".join(sentences)


def counts_sentence(meta: MatterMetadata) -> str:
    counts = meta.counts
    found = [count_of(counts[t], t) for t in DOC_TYPES if counts.get(t)]
    zero = [t for t in DOC_TYPES if counts.get(t) == 0]
    unknown = [t for t in DOC_TYPES if counts.get(t) is None]
    parts = found + ([f"no {join_words(zero, 'or')}"] if zero else [])
    sentence = f"I found {join_words(parts)}." if parts else ""
    if unknown:
        sentence += f" The site did not show how many {join_words(unknown, 'or')} there are."
    return sentence.strip()


def _file_line(doc: Document) -> str:
    when = f" ({format_date(doc.date)})" if doc.date and doc.date != doc.doc_id else ""
    return f"  - {archive_name(doc) if doc.path else doc.label}{when}"


def download_paragraphs(result: FetchResult, max_attachment_mb: float) -> List[str]:
    doc_type = result.doc_type
    total = result.total
    attached = result.documents
    n = len(attached)
    paragraphs = []

    if n == 0 and not result.oversized and not result.failed:
        return [f"There are no {doc_type} in this matter, so there is nothing to attach."]

    if n and not result.oversized and not result.failed:
        if total == n == 1:
            lead = f"I downloaded the only {SINGULAR[doc_type]} and am attaching it as a ZIP here."
        elif total == n:
            lead = f"I downloaded all {count_of(n, doc_type)} and am attaching them as a ZIP here."
        elif total is not None:
            lead = f"I downloaded {n} out of the {total} {doc_type} and am attaching them as a ZIP here."
        else:
            lead = f"I downloaded {count_of(n, doc_type)} and am attaching them as a ZIP here."
    elif n:
        of_total = f" out of the {total}" if total is not None else ""
        lead = f"I am attaching {n}{of_total} {doc_type if n != 1 else SINGULAR[doc_type]} as a ZIP here."
    else:
        tried = len(result.oversized) + len(result.failed)
        of_total = f" of the {total}" if total is not None else ""
        lead = f"I tried {tried}{of_total} {doc_type}, but none of them could be attached."
    paragraphs.append(lead)

    if attached:
        paragraphs.append("Files in the ZIP:\n" + "\n".join(_file_line(d) for d in attached))
    if result.oversized:
        k = len(result.oversized)
        paragraphs.append(
            f"{'This file was' if k == 1 else f'These {k} files were'} too large to fit under the "
            f"{max_attachment_mb:g} MB email attachment limit, so I left "
            f"{'it' if k == 1 else 'them'} out. You can download "
            f"{'it' if k == 1 else 'them'} from the UARB site:\n"
            + "\n".join(_file_line(d) for d in result.oversized)
        )
    if result.failed:
        k = len(result.failed)
        paragraphs.append(
            f"The UARB site would not let me download {'this file' if k == 1 else f'these {k} files'}:\n"
            + "\n".join(_file_line(d) for d in result.failed)
        )
    return paragraphs


def _letter(name: str, paragraphs: List[str], signature: str) -> str:
    body = "\n\n".join(p for p in paragraphs if p)
    return f"Hi {name},\n\n{body}\n\nBest,\n{signature}\n"


def compose_summary(name: str, result: FetchResult, signature: str, max_attachment_mb: float) -> str:
    meta = result.metadata
    paragraphs = download_paragraphs(result, max_attachment_mb)
    opening = f"{matter_summary(meta)} {counts_sentence(meta)} {paragraphs[0]}"
    return _letter(name, [opening] + paragraphs[1:], signature)


def compose_missing_doc_type(name: str, meta: MatterMetadata, signature: str, limit: int) -> str:
    return _letter(
        name,
        [
            f"{matter_summary(meta)} {counts_sentence(meta)}",
            "Your email didn't say which type of documents you want, so I haven't downloaded anything yet. "
            f"Reply with one of {TYPES_LIST} and I'll send up to {limit} of them as a ZIP.",
        ],
        signature,
    )


def compose_missing_matter(name: str, signature: str, doc_type: Optional[str]) -> str:
    wanted = f"the {doc_type}" if doc_type else "the documents"
    return _letter(
        name,
        [
            f"I'd be glad to fetch {wanted}, but I couldn't find a matter number in your email. "
            "Matter numbers start with M followed by five digits, for example M12205.",
            f"Please reply with the matter number and one of these document types: {TYPES_LIST}. "
            f"For example: “{EXAMPLE_REQUEST}”",
        ],
        signature,
    )


def compose_not_found(name: str, matter: str, signature: str) -> str:
    return _letter(
        name,
        [
            f"I couldn't find matter {matter} in the UARB Public Documents Database. "
            "Please check the number (the letter M followed by five digits) and send it again."
        ],
        signature,
    )


def compose_failure(name: str, matter: Optional[str], signature: str) -> str:
    what = f"the documents for {matter}" if matter else "your documents"
    return _letter(
        name,
        [
            f"Something went wrong while I was retrieving {what} from the UARB site, so I couldn't "
            "finish your request. The site may be slow or down. Please try again in a little while."
        ],
        signature,
    )
